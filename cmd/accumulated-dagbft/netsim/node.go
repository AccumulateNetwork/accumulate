package devnet

import (
	"crypto/ed25519"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"text/template"

	"github.com/libp2p/go-libp2p/core/crypto"
	"github.com/libp2p/go-libp2p/core/peer"
)

// NodeConfig holds the configuration for a single devnet node.
type NodeConfig struct {
	// ID is the node identifier (e.g., "node1").
	ID string `json:"id"`

	// ValidatorADI is the ADI URL for the validator identity.
	ValidatorADI string `json:"validatorADI"`

	// P2PPort is the libp2p listen port.
	P2PPort int `json:"p2pPort"`

	// APIPort is the API server listen port.
	APIPort int `json:"apiPort"`

	// DataDir is the node's data directory.
	DataDir string `json:"dataDir"`

	// ValidatorKey is the ed25519 validator signing key.
	ValidatorKey ed25519.PrivateKey `json:"validatorKey"`

	// P2PKey is the ed25519 key for P2P identity.
	P2PKey ed25519.PrivateKey `json:"p2pKey"`

	// DAG-BFT settings
	NumWorkers       int `json:"numWorkers"`
	DAGGCDepth       int `json:"dagGCDepth"`
	CommitBufferSize int `json:"commitBufferSize"`
}

// PeerID returns the libp2p peer ID for this node.
func (n *NodeConfig) PeerID() (peer.ID, error) {
	libp2pKey, err := crypto.UnmarshalEd25519PublicKey(n.P2PKey.Public().(ed25519.PublicKey))
	if err != nil {
		return "", fmt.Errorf("unmarshal P2P key: %w", err)
	}
	return peer.IDFromPublicKey(libp2pKey)
}

// PeerMultiaddr returns the full multiaddr for this node's P2P address.
func (n *NodeConfig) PeerMultiaddr() (string, error) {
	peerID, err := n.PeerID()
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("/ip4/127.0.0.1/tcp/%d/p2p/%s", n.P2PPort, peerID), nil
}

// ValidatorPublicKey returns the validator's public key.
func (n *NodeConfig) ValidatorPublicKey() ed25519.PublicKey {
	return n.ValidatorKey.Public().(ed25519.PublicKey)
}

// ValidatorKeyHex returns the hex-encoded validator public key.
func (n *NodeConfig) ValidatorKeyHex() string {
	return hex.EncodeToString(n.ValidatorPublicKey())
}

// Initialize creates the node's data directory and configuration files.
func (n *NodeConfig) Initialize(genesis *GenesisDoc) error {
	// Create data directory
	if err := os.MkdirAll(n.DataDir, 0755); err != nil {
		return fmt.Errorf("create data dir: %w", err)
	}

	// Write validator key
	keyPath := filepath.Join(n.DataDir, "validator.key")
	if err := os.WriteFile(keyPath, []byte(hex.EncodeToString(n.ValidatorKey)), 0600); err != nil {
		return fmt.Errorf("write validator key: %w", err)
	}

	// Write P2P key
	p2pKeyPath := filepath.Join(n.DataDir, "p2p.key")
	if err := os.WriteFile(p2pKeyPath, []byte(hex.EncodeToString(n.P2PKey)), 0600); err != nil {
		return fmt.Errorf("write P2P key: %w", err)
	}

	// Write genesis
	genesisPath := filepath.Join(n.DataDir, "genesis.json")
	if err := genesis.Save(genesisPath); err != nil {
		return fmt.Errorf("write genesis: %w", err)
	}

	// Write node config
	configPath := filepath.Join(n.DataDir, "config.toml")
	if err := n.writeConfig(configPath); err != nil {
		return fmt.Errorf("write config: %w", err)
	}

	return nil
}

// writeConfig writes the node configuration file.
func (n *NodeConfig) writeConfig(path string) error {
	tmpl, err := template.New("config").Parse(configTemplate)
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}

	f, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create file: %w", err)
	}
	defer f.Close()

	if err := tmpl.Execute(f, n); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}

	return nil
}

const configTemplate = `# DAG-BFT Node Configuration
# Generated by accumulated-dagbft devnet init

[node]
id = "{{.ID}}"
validator_adi = "{{.ValidatorADI}}"
data_dir = "{{.DataDir}}"

[p2p]
port = {{.P2PPort}}

[api]
port = {{.APIPort}}

[consensus]
num_workers = {{.NumWorkers}}
dag_gc_depth = {{.DAGGCDepth}}
commit_buffer_size = {{.CommitBufferSize}}
`
