// defaultNodeKey supplies the node (libp2p) key for a configuration that names
// none (#4490). A node's peer ID is its node key, so a key made up at each
// start is a new identity at each start.
//
//   - A core validator refuses to start: its peer ID is bound in its
//     committee and named in its peers' bootstrap lists, and a new one would
//     strand both without saying why.
//   - A follower is bound to nothing, so it is given a key, appended to its
//     configuration file as an inline raw key and logged, and every later
//     start has that identity. A follower with no TOML file to write to
//     refuses, as a validator does.
//   - Anything else (a gateway, a devnet, a test) keeps the transient key it
//     always had, which warns when it is generated.
func defaultNodeKey(cfg *Config, inst *Instance) error {
	var validator, follower bool
	for _, c := range cfg.Configurations {
		switch c.(type) {
		case *CoreValidatorConfiguration:
			validator = true
		case *FollowerConfiguration:
			follower = true
		}
	}

	switch {
	case validator:
		return errors.BadRequest.WithFormat("%s has no [p2p.key]: a validator's peer ID is its node key, bound in its committee and its peers' bootstrap lists, so it will not start under a new one; add the node key (accumulated init writes it inline)", cfg.describe())

	case follower:
		ext := filepath.Ext(cfg.file)
		if cfg.file == "" || cfg.fs != nil || (ext != ".toml" && ext != ".tml") {
			return errors.BadRequest.WithFormat("%s has no [p2p.key] and cannot be written to: add a node key so the follower keeps one peer ID", cfg.describe())
		}
		_, sk, err := ed25519.GenerateKey(rand.Reader)
		if err != nil {
			return err
		}
		key := &RawPrivateKey{Address: address.FromED25519PrivateKey(sk).String()}

		// Append rather than rewrite: the file keeps the operator's text,
		// comments and environment references as they are.
		f, err := os.OpenFile(cfg.file, os.O_APPEND|os.O_WRONLY, 0)
		if err != nil {
			return errors.UnknownError.WithFormat("write the follower's node key: %w", err)
		}
		_, err = fmt.Fprintf(f, "\n# Node key generated by accumulated: this follower's peer ID (#4490).\n[p2p.key]\ntype = \"raw\"\naddress = %q\n", key.Address)
		if cerr := f.Close(); err == nil {
			err = cerr
		}
		if err != nil {
			return errors.UnknownError.WithFormat("write the follower's node key: %w", err)
		}
		cfg.P2P.Key = key
		inst.logger.Warn("The configuration had no node key; generated one and wrote it into the configuration, so this follower keeps one peer ID", "file", cfg.file)
		return nil

	default:
		cfg.P2P.Key = new(TransientPrivateKey)
		return nil
	}
}

func (c *Config) describe() string {
	if c.file == "" {
		return "the configuration"
	}
	return c.file
}

func (k *RawPrivateKey) get(inst *Instance) (address.Address, error) {
	inst.logger.Info("Loading RawPrivateKey", "address", k.Address)
	addr, err := address.Parse(k.Address)
	if err != nil {
		inst.logger.Error("Failed to parse RawPrivateKey address", "address", k.Address, "error", err)
		return nil, err
	}
	inst.logger.Info("RawPrivateKey loaded successfully", "address", k.Address)
	return addr, nil
}

func (k *TransientPrivateKey) get(inst *Instance) (address.Address, error) {
	if k.key != nil {
		return k.key, nil
	}

	inst.logger.WarnContext(inst.context, "Generating a new key. This is highly discouraged for permanent infrastructure.")
	pk, sk, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		panic(err)
	}
	k.key = &address.PrivateKey{
		PublicKey: address.PublicKey{
			Type: protocol.SignatureTypeED25519,
			Key:  pk,
		},
		Key: sk,
	}
	return k.key, nil
}

func (k *PrivateKeySeed) get(inst *Instance) (address.Address, error) {
	if k.key != nil {
		return k.key, nil
	}

	inst.logger.WarnContext(inst.context, "Generating a new key from a seed. This is not at all secure.")
	h := k.Seed.Hash()
	sk := ed25519.NewKeyFromSeed(h[:])
	k.key = &address.PrivateKey{
		PublicKey: address.PublicKey{
			Type: protocol.SignatureTypeED25519,
			Key:  sk[32:],
		},
		Key: sk,
	}
	return k.key, nil
}
